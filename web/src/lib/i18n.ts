export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(ui: UiLang): T {
  const dict = DICTS[ui] ?? en;
  return (key, vars) => {
    let s = dict[key] ?? en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

/** Error code from the API → message in the interface language. */
export function errorText(t: T, code: string, fallback: string): string {
  const key = `err_${code}` as Key;
  return key in en ? t(key) : fallback;
}
